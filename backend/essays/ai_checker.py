    total_score = sum(
        float(criterion["score"])
        for criterion in cleaned_criteria
    )

    if not 0 <= total_score <= 24:
        raise ValueError(
            f"Hisoblangan total_score noto‘g‘ri: {total_score}"
        )

    result["total_score"] = (
        int(total_score) if total_score.is_integer() else total_score
    )


    # =====================================================
    # REVIEW
    # =====================================================

    result["review"] = str(
        result.get("review") or ""
    ).strip()


    # =====================================================
    # ERRORSNI TEKSHIRISH
    # =====================================================

    errors = result.get("errors", [])

    if not isinstance(errors, list):
        errors = []

    cleaned_errors = []

    for error in errors:

        if not isinstance(error, dict):
            continue

        fragment = str(error.get("fragment") or "").strip()

        if not fragment:
            continue

        # AI essayda yo‘q fragmentni qaytarmasligi kerak.
        if fragment not in essay_text:
            continue

        cleaned_errors.append({
            "fragment": fragment,
            "type": str(error.get("type") or "Языковая ошибка").strip(),
            "correction": str(error.get("correction") or "").strip(),
            "explanation": str(error.get("explanation") or "").strip(),
        })

    result["errors"] = cleaned_errors


    # =====================================================
    # RECOMMENDATIONS
    # =====================================================

    recommendations = result.get("recommendations", [])

    if not isinstance(recommendations, list):
        recommendations = []

    result["recommendations"] = [
        str(item).strip()
        for item in recommendations
        if str(item).strip()
    ]

    # =====================================================
    # FINAL RESULT
    # =====================================================

    print()
    print("==============================")
    print("======= AI CHECK SUCCESS =====")
    print("==============================")
    print("Total score:", result["total_score"])
    print(
        "Criteria:",
        len(result["criteria"])
    )
    print(
        "Errors:",
        len(result["errors"])
        if isinstance(result["errors"], list)
        else 0
    )
    print("==============================")
    print()

    return result